#!/usr/bin/env python3
"""
Split the koko avatar (art-src/koko-avatar.png) into the two layers used by
the product heroes, so the K and O "eyes" can follow the pointer:

  - an eyeless body: the K and O are painted out with the surrounding ivory
    (OpenCV inpainting), rendered as WebP at 320/640/1024 px plus a 480 px PNG
    fallback into src/static/assets/img/koko/;
  - the K and O as vector paths traced from the same pixels (potrace), written
    to src/data/koko-eyes.json (viewBox 0 0 1024 1024, one path per glyph).

The original about-page avatar files are left untouched. Run manually when the
avatar changes:

    python3 scripts/assets/koko.py

Requires numpy, opencv-python-headless, potracer and Pillow.
"""
import json
from pathlib import Path

import cv2
import numpy as np
import potrace
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "art-src/koko-avatar.png"
OUT = ROOT / "src/static/assets/img/koko"
EYES = ROOT / "src/data/koko-eyes.json"


def main():
    im = cv2.imread(str(SRC), cv2.IMREAD_UNCHANGED)
    assert im.shape[:2] == (1024, 1024) and im.shape[2] == 4, "expected a 1024x1024 RGBA master"
    b, g, r, a = [c.astype(np.float32) for c in cv2.split(im)]
    luma = 0.299 * r + 0.587 * g + 0.114 * b

    # The glyphs: solid near-black shapes on the ivory face.
    ink = ((luma < 128) & (a > 200)).astype(np.uint8)
    n, lab, stats, _ = cv2.connectedComponentsWithStats(ink)
    glyphs = sorted([i for i in range(1, n) if stats[i, cv2.CC_STAT_AREA] > 5000], key=lambda i: stats[i, cv2.CC_STAT_LEFT])
    assert len(glyphs) == 2, f"expected K and O, found {len(glyphs)} shapes"

    # Body: paint out the glyphs (including their anti-aliased rims and any
    # faint halo) with a smooth model of the face colour: a quadratic surface
    # fitted per channel to the face pixels around them. Inpainting alone
    # leaves a ghost of the strokes; the fitted surface leaves none.
    near = cv2.dilate(ink, np.ones((41, 41), np.uint8))
    rim = ((luma < 241) & (a > 200)).astype(np.uint8) & near
    mask = cv2.dilate(rim | ink, np.ones((9, 9), np.uint8))
    ring = cv2.dilate(mask, np.ones((61, 61), np.uint8)) & (1 - mask) & (luma > 236).astype(np.uint8) & (a > 250).astype(np.uint8)
    yy, xx = np.mgrid[0:1024, 0:1024].astype(np.float32) / 1024
    def feats(x, y):
        return np.stack([np.ones_like(x), x, y, x * x, x * y, y * y], -1)
    sel = ring.astype(bool)
    A = feats(xx[sel], yy[sel])
    bgr = im[:, :, :3].astype(np.float32)
    model = np.zeros_like(bgr)
    F = feats(xx, yy)
    for c in range(3):
        coef, *_ = np.linalg.lstsq(A, bgr[:, :, c][sel], rcond=None)
        model[:, :, c] = F @ coef
    m = cv2.GaussianBlur(mask.astype(np.float32), (0, 0), 4)[..., None]
    m = np.clip(m * 1.6, 0, 1)
    body = np.clip(bgr * (1 - m) + model * m, 0, 255).astype(np.uint8)
    rgba = cv2.cvtColor(np.dstack([body, im[:, :, 3]]), cv2.COLOR_BGRA2RGBA)
    body_img = Image.fromarray(rgba, "RGBA")

    OUT.mkdir(parents=True, exist_ok=True)
    for w in (320, 640, 1024):
        body_img.resize((w, w), Image.LANCZOS).save(OUT / f"body-{w}.webp", quality=88, method=6)
    body_img.resize((480, 480), Image.LANCZOS).save(OUT / "body-480.png", optimize=True)

    # Eyes: trace each glyph.
    paths = []
    for i in glyphs:
        # The 50% luma threshold sits on the middle of the anti-aliased edge.
        bm = potrace.Bitmap(lab != i)  # potracer traces the dark (False) pixels
        plist = bm.trace(turdsize=20, alphamax=1.1, opticurve=True, opttolerance=0.3)
        d = []
        for curve in plist:
            s = curve.start_point
            d.append(f"M{s.x:.1f} {s.y:.1f}")
            for seg in curve.segments:
                if seg.is_corner:
                    d.append(f"L{seg.c.x:.1f} {seg.c.y:.1f}L{seg.end_point.x:.1f} {seg.end_point.y:.1f}")
                else:
                    d.append(f"C{seg.c1.x:.1f} {seg.c1.y:.1f} {seg.c2.x:.1f} {seg.c2.y:.1f} {seg.end_point.x:.1f} {seg.end_point.y:.1f}")
            d.append("Z")
        paths.append("".join(d))

    x0 = min(stats[i, cv2.CC_STAT_LEFT] for i in glyphs)
    y0 = min(stats[i, cv2.CC_STAT_TOP] for i in glyphs)
    x1 = max(stats[i, cv2.CC_STAT_LEFT] + stats[i, cv2.CC_STAT_WIDTH] for i in glyphs)
    y1 = max(stats[i, cv2.CC_STAT_TOP] + stats[i, cv2.CC_STAT_HEIGHT] for i in glyphs)
    data = {
        "$comment": "Generated by scripts/assets/koko.py from art-src/koko-avatar.png. Do not edit by hand.",
        "viewBox": [0, 0, 1024, 1024],
        "fill": "#111312",
        "center": [round((x0 + x1) / 2, 1), round((y0 + y1) / 2, 1)],
        "paths": {"k": paths[0], "o": paths[1]},
    }
    EYES.write_text(json.dumps(data, indent=2) + "\n")
    print("wrote", OUT, "and", EYES, data["center"])


if __name__ == "__main__":
    main()
